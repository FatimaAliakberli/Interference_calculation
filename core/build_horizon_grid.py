#!/usr/bin/env python3
"""
Build a precomputed horizon-profile dataset covering Azerbaijan (or any
bounding box) on a regular geodesic grid, so that a specific location can
later be looked up by snapping to the nearest precomputed grid point
instead of recalculating from scratch every time.

Grid points are generated by geodesic stepping (pyproj Geod), spaced
`--spacing-km` apart, sweeping south -> north, west -> east. Points with
no valid DEM coverage (e.g. outside the raster / sea / nodata) are
skipped automatically, so if your DEM is clipped to Azerbaijan you get a
dataset that naturally follows the country's footprint without needing a
separate boundary shapefile.

NOTE ON COST: computing a full horizon profile (default: 5 degree
azimuth steps, 100 km search radius, 0.5 km step) at EVERY grid cell
across a country is very heavy - tens of millions of DEM reads. The
defaults below are intentionally coarser for the batch build
(10 degree azimuth, 40 km radius, 1 km step). Tune with the flags below
to trade accuracy for runtime. Your interactive/single-station script
can still use fine settings for a one-off query.

Usage:
    python build_horizon_grid.py --dem azerbaijan_dem.tif --db horizon_grid.db

Azerbaijan's rough bounding box (WGS84) is used by default:
    lon: 44.7 to 50.6   lat: 38.3 to 41.95
Adjust with --lat-min/--lat-max/--lon-min/--lon-max if your DEM covers a
different or smaller area.
"""
import argparse
import json
import multiprocessing as mp
import sqlite3
import time

from pyproj import Geod

# Default bounding box: Azerbaijan, WGS84 (approximate, generous padding)
DEFAULT_LAT_MIN = 38.3
DEFAULT_LAT_MAX = 41.95
DEFAULT_LON_MIN = 44.7
DEFAULT_LON_MAX = 50.6


def generate_grid_points(lat_min, lat_max, lon_min, lon_max, spacing_km, geod):
    """
    Generate grid points spaced `spacing_km` apart using true geodesic
    distances (not naive degree steps, which distort badly at higher
    latitudes / larger areas). Sweeps south -> north, and within each
    row west -> east.
    """
    points = []
    step_m = spacing_km * 1000.0

    row_lon, row_lat = lon_min, lat_min
    row_idx = 0
    while row_lat <= lat_max:
        lon, lat = row_lon, row_lat
        col_idx = 0
        while lon <= lon_max:
            points.append({'row': row_idx, 'col': col_idx, 'lat': lat, 'lon': lon})
            lon, lat, _ = geod.fwd(lon, lat, 90.0, step_m)  # step east
            col_idx += 1
        row_lon, row_lat, _ = geod.fwd(row_lon, row_lat, 0.0, step_m)  # step north
        row_idx += 1

    return points


# --- multiprocessing worker state (one DEM handle per worker process) ---
_worker_src = None
_worker_geod = None
_worker_params = None


def _init_worker(dem_path, params):
    global _worker_src, _worker_geod, _worker_params
    import rasterio
    _worker_src = rasterio.open(dem_path)
    _worker_geod = Geod(ellps='WGS84')
    _worker_params = params


def _compute_point(point):
    # Support both `python core/build_horizon_grid.py` (top-level import) and
    # `from core.build_horizon_grid import ...` (package import). Worker
    # processes re-import this module fresh (spawn) or inherit it via fork,
    # so the fallback needs to work in a bare subprocess too.
    try:
        from core.horizon_core import calculate_horizon_profile, safe_read_dem
    except ImportError:
        from horizon_core import calculate_horizon_profile, safe_read_dem

    lat, lon = point['lat'], point['lon']

    # Cheap pre-check: skip points with no DEM coverage at all
    # (outside the raster, sea, nodata, etc.)
    if safe_read_dem(_worker_src, lon, lat) is None:
        return None

    results, station_alt = calculate_horizon_profile(
        _worker_src, _worker_geod, lat, lon,
        station_alt=0,
        max_distance_km=_worker_params['max_distance_km'],
        step_km=_worker_params['step_km'],
        azimuth_increment=_worker_params['azimuth_increment'],
    )
    # station_alt=0 passed in above is a sentinel, not a real altitude -
    # calculate_horizon_profile() (horizon_core.py) treats it as "look this
    # up from the DEM" and returns the actual DEM-read elevation at
    # (lat, lon) here. That resolved value (not 0) is what gets stored
    # below in the 'station_alt' column, and is what query_horizon.py's
    # query_location() returns as 'station_alt' (and 'altitude') for a
    # given lookup - so the grid DB already carries real per-point
    # altitude; no schema change was needed here.

    return {
        'row': point['row'], 'col': point['col'],
        'lat': lat, 'lon': lon, 'station_alt': station_alt,
        'profile': results,
    }


def _init_db(db_path):
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()
    cur.execute("""
        CREATE TABLE IF NOT EXISTS horizon_profiles (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            row_idx INTEGER,
            col_idx INTEGER,
            lat REAL,
            lon REAL,
            station_alt REAL,
            max_distance_km REAL,
            step_km REAL,
            azimuth_increment INTEGER,
            profile_json TEXT
        )
    """)
    cur.execute("""
        CREATE TABLE IF NOT EXISTS grid_meta (
            key TEXT PRIMARY KEY,
            value TEXT
        )
    """)
    cur.execute("CREATE INDEX IF NOT EXISTS idx_lat_lon ON horizon_profiles(lat, lon)")
    conn.commit()
    return conn


def build_grid(dem_path, db_path, lat_min, lat_max, lon_min, lon_max,
                spacing_km, max_distance_km, step_km, azimuth_increment,
                workers=None):
    geod = Geod(ellps='WGS84')
    grid_points = generate_grid_points(lat_min, lat_max, lon_min, lon_max,
                                        spacing_km, geod)
    print(f"Generated {len(grid_points)} candidate grid points "
          f"({spacing_km} km spacing) over bbox "
          f"lat[{lat_min},{lat_max}] lon[{lon_min},{lon_max}]")

    params = {
        'max_distance_km': max_distance_km,
        'step_km': step_km,
        'azimuth_increment': azimuth_increment,
    }

    conn = _init_db(db_path)
    cur = conn.cursor()
    for key, value in [
        ('spacing_km', spacing_km), ('lat_min', lat_min), ('lat_max', lat_max),
        ('lon_min', lon_min), ('lon_max', lon_max),
        ('max_distance_km', max_distance_km), ('step_km', step_km),
        ('azimuth_increment', azimuth_increment),
    ]:
        cur.execute("INSERT OR REPLACE INTO grid_meta (key, value) VALUES (?, ?)",
                     (key, str(value)))
    conn.commit()

    workers = workers or mp.cpu_count()
    print(f"Computing profiles with {workers} worker process(es)...")

    start = time.time()
    kept, skipped = 0, 0

    with mp.Pool(processes=workers, initializer=_init_worker,
                 initargs=(dem_path, params)) as pool:
        for i, record in enumerate(pool.imap_unordered(_compute_point, grid_points, chunksize=4), 1):
            if record is None:
                skipped += 1
            else:
                cur.execute("""
                    INSERT INTO horizon_profiles
                    (row_idx, col_idx, lat, lon, station_alt,
                     max_distance_km, step_km, azimuth_increment, profile_json)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, (
                    record['row'], record['col'], record['lat'], record['lon'],
                    record['station_alt'], max_distance_km, step_km, azimuth_increment,
                    json.dumps(record['profile']),
                ))
                kept += 1

            if i % 50 == 0 or i == len(grid_points):
                conn.commit()
                elapsed = time.time() - start
                print(f"  {i}/{len(grid_points)} points processed "
                      f"({kept} kept, {skipped} no-coverage) - {elapsed:.1f}s elapsed")

    conn.commit()
    conn.close()

    print(f"\nDone. {kept} grid points with valid DEM coverage saved to {db_path}")
    print(f"({skipped} candidate points fell outside DEM coverage and were skipped)")


def main():
    parser = argparse.ArgumentParser(
        description="Precompute a horizon-profile grid dataset over a bounding box (default: Azerbaijan)")
    parser.add_argument("--dem", required=True, help="Path to DEM GeoTIFF file (EPSG:4326)")
    parser.add_argument("--db", required=True, help="Output SQLite database path")
    parser.add_argument("--lat-min", type=float, default=DEFAULT_LAT_MIN)
    parser.add_argument("--lat-max", type=float, default=DEFAULT_LAT_MAX)
    parser.add_argument("--lon-min", type=float, default=DEFAULT_LON_MIN)
    parser.add_argument("--lon-max", type=float, default=DEFAULT_LON_MAX)
    parser.add_argument("--spacing-km", type=float, default=5.0, help="Grid spacing in km")
    parser.add_argument("--max-dist", type=float, default=40.0,
                         help="Horizon search radius per grid point (km). Kept smaller than "
                              "single-station default (100km) to keep batch runtime sane.")
    parser.add_argument("--step", type=float, default=1.0,
                         help="Radial step size per azimuth (km). Coarser than single-station default (0.5km).")
    parser.add_argument("--increment", type=int, default=10,
                         help="Azimuth increment in degrees. Coarser than single-station default (5deg).")
    parser.add_argument("--workers", type=int, default=None,
                         help="Number of worker processes (default: CPU count)")
    args = parser.parse_args()

    build_grid(
        dem_path=args.dem, db_path=args.db,
        lat_min=args.lat_min, lat_max=args.lat_max,
        lon_min=args.lon_min, lon_max=args.lon_max,
        spacing_km=args.spacing_km,
        max_distance_km=args.max_dist, step_km=args.step,
        azimuth_increment=args.increment,
        workers=args.workers,
    )


if __name__ == "__main__":
    main()